"""
Ollama Local LLM Client with DeepSeek/Qwen Thinking Tag Filter.
Communicates with the local Ollama API to extract semantic beats, scene splits, and emphasis words in strict JSON format.
"""
import re
import json
import requests
from typing import Dict, Any, Optional
from src.core.config_loader import load_system_config


class OllamaClient:
    def __init__(self, base_url: Optional[str] = None, model: Optional[str] = None):
        cfg = load_system_config().get("ollama", {})
        self.base_url = (base_url or cfg.get("base_url", "http://localhost:11434")).rstrip("/")
        self.model = model or cfg.get("model", "qwen3.5:9b")
        self.timeout = 10

    def generate_json(self, prompt: str, system_prompt: Optional[str] = None) -> Dict[str, Any]:
        """
        Sends a generation request to Ollama enforcing JSON format output.
        """
        endpoint = f"{self.base_url}/api/generate"
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            "options": {
                "num_predict": 3000,
                "temperature": 0.1
            }
        }
        if system_prompt:
            payload["system"] = system_prompt

        try:
            resp = requests.post(endpoint, json=payload, timeout=self.timeout)
            resp.raise_for_status()
            data = resp.json()
            raw_response = data.get("response", "{}")

            # Strip thinking tags if generated by Qwen/DeepSeek
            clean = re.sub(r"<think>.*?</think>", "", raw_response, flags=re.DOTALL).strip()
            
            # Strip markdown json block fences if present
            if clean.startswith("```json"):
                clean = clean[7:]
            if clean.startswith("```"):
                clean = clean[3:]
            if clean.endswith("```"):
                clean = clean[:-3]
            clean = clean.strip()

            # Find the outer JSON object boundaries {...}
            start_brace = clean.find("{")
            end_brace = clean.rfind("}")
            if start_brace != -1 and end_brace != -1:
                clean = clean[start_brace:end_brace+1]

            return json.loads(clean)

        except requests.exceptions.RequestException as e:
            raise ConnectionError(f"Failed to communicate with Ollama at {endpoint}: {e}")
